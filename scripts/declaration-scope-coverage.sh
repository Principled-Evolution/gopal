#!/usr/bin/env bash
# Generate and check the field-by-field EU AI Act declaration scope analysis.
set -euo pipefail

cd "$(dirname "$0")/.."

CLASSIFICATION="docs/declaration-scope-classification.json"
REPORT="docs/declaration-scope.md"
DECLARATIONS="docs/declarations.md"
MANIFEST="dist/playground/manifest.json"
SOURCE_URL="https://eur-lex.europa.eu/eli/reg/2024/1689/2026-07-27/eng"
MODE="write"

if [ "$#" -gt 1 ]; then
	echo "Usage: scripts/declaration-scope-coverage.sh [--check]" >&2
	exit 2
fi
if [ "$#" -eq 1 ]; then
	case "$1" in
		"--check") MODE="check" ;;
		*) echo "Usage: scripts/declaration-scope-coverage.sh [--check]" >&2; exit 2 ;;
	esac
fi

for tool in jq awk cmp mktemp; do
	command -v "$tool" >/dev/null 2>&1 || {
		echo "error: $tool is required and not on PATH" >&2
		exit 1
	}
done

# The manifest is ignored build output. Rebuild it on every run so --check
# cannot silently validate against fields from an earlier checkout or build.
echo "Building current playground manifest…" >&2
scripts/build-playground.sh >/dev/null

if ! jq -e '
	(.organisation | type == "object")
	and (.system | type == "object")
	and ([.organisation, .system] | map(to_entries) | add
		| map(.value | type == "string" and length > 0)
		| all)
' "$CLASSIFICATION" >/dev/null; then
	echo "error: classification must contain non-empty organisation and system maps" >&2
	exit 1
fi

duplicates="$(jq -r '
	(.organisation | keys) as $organisation
	| (.system | keys) as $system
	| [$organisation[] | select(. as $field | $system | index($field))]
	| .[]?
' "$CLASSIFICATION")"
if [ -n "$duplicates" ]; then
	echo "error: fields appear in both classification groups:" >&2
	printf '  %s\n' "$duplicates" >&2
	exit 1
fi

unknown="$(jq -r --slurpfile c "$CLASSIFICATION" '
	[.frameworks[]
		| select(.id == "international/eu_ai_act")
		| .policies[].declared_fields[]
	] | unique as $fields
	| (($c[0].organisation | keys) + ($c[0].system | keys)) as $classified
	| ($classified - $fields)[]
' "$MANIFEST")"
if [ -n "$unknown" ]; then
	echo "error: classification names fields that are not declared by EU AI Act policies:" >&2
	printf '  %s\n' "$unknown" >&2
	exit 1
fi

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
report_tmp="$tmpdir/declaration-scope.md"
summary_tmp="$tmpdir/declaration-scope-summary.md"
declarations_tmp="$tmpdir/declarations.md"

jq -r --slurpfile c "$CLASSIFICATION" --arg source_url "$SOURCE_URL" '
	(.frameworks[]
		| select(.id == "international/eu_ai_act")
		| [.policies[].declared_fields[]]
		| unique) as $fields
	| ($c[0].organisation) as $organisation
	| ($c[0].system) as $system
	| ((($organisation | keys) + ($system | keys)) | unique) as $classified
	| ($fields - $classified) as $remaining
	| (([$organisation, $system]
		| map(to_entries[])
		| map(select(.value | test("uncertain:"; "i")))
		| length)) as $uncertain
	| def field_table($group):
		if ($group | length) == 0 then
			"| (none) | - |"
		else
			"| Field | Rationale |\n| --- | --- |\n"
			+ ($group
				| to_entries
				| sort_by(.key)
				| map("| \(.key) | \(.value | gsub("\\|"; "\\\\|") | gsub("[\r\n]+"; " ")) |")
				| join("\n"))
		end;
	[
		"# EU AI Act declaration scope: first batch",
		"",
		"**Generated by scripts/declaration-scope-coverage.sh from docs/declaration-scope-classification.json and the playground manifest. Do not edit by hand.**",
		"",
		"Source: [Regulation (EU) 2024/1689, consolidated text](\($source_url)).",
		"",
		"Organisation/product-level means a fact maintained once for an organisation or marketed product and reused across deployments. Per-system means a fact that depends on the particular AI system, its market placement, or its deployment. The Act does not always draw the product-versus-system boundary at the same granularity; rationales marked **Uncertain** are open for maintainer review. This is a field-level interpretation, not legal advice.",
		"",
		"## Progress",
		"",
		"| | Fields |",
		"| --- | ---: |",
		"| Classified | \($classified | length) / \($fields | length) |",
		"| Organisation/product-level | \($organisation | keys | length) |",
		"| Per-system | \($system | keys | length) |",
		"| Marked uncertain | \($uncertain) |",
		"| Not yet classified | \($remaining | length) |",
		"",
		"## Organisation or product level",
		"",
		field_table($organisation),
		"",
		"## Per system",
		"",
		field_table($system),
		"",
		"## Remaining fields by prefix",
		"",
		"These fields are outside this first review batch.",
		"",
		"| Prefix | Fields remaining |",
		"| --- | ---: |"
	]
	+ ($remaining
		| sort
		| group_by(split(".")[0])
		| map("| \(.[0] | split(".")[0]) | \(length) |"))
	| join("\n")
' "$MANIFEST" >"$report_tmp"

jq -r --slurpfile c "$CLASSIFICATION" '
	(.frameworks[]
		| select(.id == "international/eu_ai_act")
		| [.policies[].declared_fields[]]
		| unique) as $fields
	| ($c[0].organisation) as $organisation
	| ($c[0].system) as $system
	| ((($organisation | keys) + ($system | keys)) | unique | length) as $classified
	| (([$organisation, $system]
		| map(to_entries[])
		| map(select(.value | test("uncertain:"; "i")))
		| length)) as $uncertain
	| "The first field-by-field batch classifies **\($classified) of \($fields | length) unique declared fields**: **\($organisation | keys | length) organisation/product-level** and **\($system | keys | length) per-system**. **\($uncertain) cases are marked uncertain** for review; \($fields | length - $classified) fields remain unclassified. See the [generated field-by-field classification](declaration-scope.md)."
' "$MANIFEST" >"$summary_tmp"

start_marker="<!-- DECLARATION_SCOPE_SUMMARY:START -->"
end_marker="<!-- DECLARATION_SCOPE_SUMMARY:END -->"
awk -v start="$start_marker" -v end="$end_marker" -v summary_file="$summary_tmp" '
	$0 == start {
		if (seen_start || inside) {
			print "error: duplicate declaration scope summary start marker" > "/dev/stderr"
			exit 1
		}
		seen_start = 1
		inside = 1
		print
		while ((getline line < summary_file) > 0) print line
		close(summary_file)
		next
	}
	$0 == end {
		if (!inside) {
			print "error: declaration scope summary end marker has no start" > "/dev/stderr"
			exit 1
		}
		inside = 0
		print
		seen_end = 1
		next
	}
	!inside { print }
	END {
		if (!seen_start || !seen_end || inside) {
			print "error: declaration scope summary markers are missing or unbalanced" > "/dev/stderr"
			exit 1
		}
	}
' "$DECLARATIONS" >"$declarations_tmp"

if [ "$MODE" = "check" ]; then
	if [ ! -f "$REPORT" ] || ! cmp -s "$report_tmp" "$REPORT"; then
		echo "error: $REPORT is out of date. Run scripts/declaration-scope-coverage.sh" >&2
		exit 1
	fi
	if ! cmp -s "$declarations_tmp" "$DECLARATIONS"; then
		echo "error: the generated summary in $DECLARATIONS is out of date. Run scripts/declaration-scope-coverage.sh" >&2
		exit 1
	fi
	echo "Declaration scope classification and summary are up to date."
else
	cp "$report_tmp" "$REPORT"
	cp "$declarations_tmp" "$DECLARATIONS"
	echo "Updated $REPORT and the generated summary in $DECLARATIONS."
fi
